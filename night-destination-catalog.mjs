function compactKey(value = "") {
  return String(value).normalize("NFKC").toLowerCase().replace(/[\u200c\s]+/g, "-").replace(/[^\p{L}\p{N}-]+/gu, "").replace(/-+/g, "-").replace(/^-|-$/g, "");
}
function destinationType(name, query) {
  const text = `${name} | ${query}`;
  if (/(?:روستا|Village|Masuleh|Abyaneh|Kandovan|Filband|Palangan|Kandelous|Hallstatt)/i.test(text)) return "VILLAGE";
  if (/(?:جاده|Road)/i.test(text)) return "SCENIC_ROUTE";
  if (/(?:جزیره|Island|Bali|Phuket|Zanzibar|Mallorca|Macau|Hong Kong)/i.test(text)) return "ISLAND";
  if (/(?:کویر|بیابان|دریاچه|آبشار|جنگل|کوه|تنگه|دره|غار|خلیج|دشت|تالاب|ساحل|پارک ملی|National Park|Desert|Lake|Waterfall|Forest|Mountain|Canyon|Bay|Wetland|Coast|Great Barrier Reef|Uluru|Wadi Rum|Grand Canyon|Yellowstone|Banff|Cappadocia)/i.test(text)) return "NATURE";
  if (/(?:کاخ|قلعه|ارگ|بازار|میدان|باغ|آرامگاه|مقبره|مسجد|کلیسا|گنبد|رصدخانه|پرسپولیس|پاسارگاد|چغازنبیل|شهر سوخته|تخت سلیمان|بیستون|سازه‌های آبی|دیوار بزرگ|تاج محل|آنگکور وات|ماچو پیچو|Palace|Castle|Citadel|Bazaar|Square|Garden|Mosque|Cathedral|Monastery|Tomb|Dome|Persepolis|Pasargadae|Heritage|Great Wall|Taj Mahal|Angkor Wat|Machu Picchu|Neuschwanstein)/i.test(text)) return "HERITAGE";
  return "CITY";
}
