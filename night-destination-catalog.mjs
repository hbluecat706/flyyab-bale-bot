export function nightDestinationCatalogStats(catalog = NIGHT_DESTINATIONS) {
  const active = catalog.filter((item) => item.status === "ACTIVE");
  const byScope = Object.fromEntries(["IRAN","WORLD"].map((scope) => [scope, active.filter((item) => item.scope === scope).length]));
  const byType = [...new Set(active.map((item) => item.type))].sort().reduce((acc, type) => (acc[type] = active.filter((item) => item.type === type).length, acc), {});
  const byTier = [...new Set(active.map((item) => item.tier))].sort().reduce((acc, tier) => (acc[tier] = active.filter((item) => item.tier === tier).length, acc), {});
  return { total: catalog.length, active: active.length, byScope, byType, byTier };
}
